import { ISSUE_CATEGORIES } from '@/engine/issues/issue';
import type { ChecksOnlyResult } from './checksOnlyResult';
import type { ModelResult } from './modelResult';
import { CATEGORY_LABELS } from './score/categoryLabels';
import { formatPercent } from './score/formatPercent';
import { pooledSuggestionAccuracy } from './score/pooledSuggestionAccuracy';
import { toMarkdownTable } from './toMarkdownTable';

/**
 * The README's accuracy table, written only from result files. Precision is how many claims were
 * right; recall is how many planted errors were found. A cost is a lower bound when a call came
 * back without one.
 */
export function buildSummary({
  checksOnly,
  models,
}: {
  checksOnly: ChecksOnlyResult;
  models: readonly ModelResult[];
}): string {
  const sorted = [...models].sort((first, second) =>
    first.model.localeCompare(second.model)
  );
  const header = [
    'Run',
    ...ISSUE_CATEGORIES.map((category) => CATEGORY_LABELS[category]),
    'Suggestion accuracy',
    'Cost per run',
    'Time per run',
  ];
  const rows = [
    [
      'Checks only',
      ...formatCategories(checksOnly.scores),
      formatPercent(pooledSuggestionAccuracy(checksOnly.scores)),
      '$0',
      'n/a',
    ],
    ...sorted.map((result) => [
      result.model,
      ...formatCategories(result.scores),
      formatPercent(pooledSuggestionAccuracy(result.scores)),
      `${result.callsWithoutCost > 0 ? '≥ ' : ''}$${result.cost.toFixed(4)}`,
      `${(result.wallMs / 1000).toFixed(1)} s`,
    ]),
  ];

  return [
    '# Eval summary',
    '',
    `Generated by \`yarn eval --summary\` from the result files in this folder. Dataset \`${checksOnly.dataset}\`, seed ${checksOnly.seed}, ${checksOnly.rows} rows. Each cell is precision (P) and recall (R).`,
    '',
    ...toMarkdownTable([header, ...rows]),
    '',
    '## Runs',
    '',
    ...toMarkdownTable([
      ['Model', 'Date', 'Calls', 'Tokens', 'Failed tasks'],
      ...sorted.map((result) => [
        result.model,
        result.date,
        String(result.calls),
        result.tokens.toLocaleString('en-US'),
        formatFailures(result),
      ]),
    ]),
    '',
  ].join('\n');
}

function formatCategories(scores: ChecksOnlyResult['scores']): string[] {
  return ISSUE_CATEGORIES.map((category) => {
    const { precision, recall } = scores[category];

    return `P ${formatPercent(precision)} · R ${formatPercent(recall)}`;
  });
}

function formatFailures({
  failedTasks,
  callsWithoutCost,
}: ModelResult): string {
  const failures = failedTasks.map(({ task, reason }) => `${task}: ${reason}`);
  const unpriced =
    callsWithoutCost > 0
      ? [
          `${callsWithoutCost} ${callsWithoutCost === 1 ? 'call' : 'calls'} without a cost`,
        ]
      : [];
  const notes = [...failures, ...unpriced];

  return notes.length === 0 ? 'none' : notes.join('; ');
}
